import { NodeIO } from "@gltf-transform/core";
import { existsSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import * as THREE from "three";
import { GLTFLoader } from "three/examples/jsm/loaders/GLTFLoader.js";
import { EDITIONS } from "../../src/characters/figures";
import { FIGURE_HEIGHT } from "../../src/characters/Figure";
import { paths } from "../tripo/env";
import { log } from "../tripo/log";
import { gameFileBase } from "../tripo/pipeline";

/**
 * Samples where each clip carries the hips (30 samples/s), in the same normalised figure space RiggedFigure renders
 * in (feet on y = 0, centred on the first idle frame, FIGURE_HEIGHT tall). Cameras use it to follow a dancer whose
 * clip drifts. Pure data, so the film stays deterministic → src/characters/clip-tracks.json.
 */
const OUT = path.join(paths.root, "src", "characters", "clip-tracks.json");

const load = async (file: string) => {
  // three's loader needs no textures for skeleton maths (and cannot decode images in Node)
  const io = new NodeIO();
  const doc = await io.read(file);
  for (const t of doc.getRoot().listTextures()) t.dispose();
  const bytes = await io.writeBinary(doc);
  const ab = bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength) as ArrayBuffer;
  return new Promise<{ scene: THREE.Group; animations: THREE.AnimationClip[] }>((res, rej) => new GLTFLoader().parse(ab, "", res as never, rej));
};

export const writeClipTracks = async () => {
  const tracks: Record<string, Record<string, number[][]>> = {};
  for (const e of EDITIONS) {
    const file = `${gameFileBase(e.id, "animated")}.glb`;
    if (!existsSync(file)) continue;
    const { scene, animations } = await load(file);
    const mixer = new THREE.AnimationMixer(scene);
    const hips = scene.getObjectByName("mixamorigHips");
    if (!hips) {
      log.warn(`${e.id}: no mixamorig:Hips joint — skipping clip tracks`);
      continue;
    }
    const pose = (clip: THREE.AnimationClip, t: number) => {
      mixer.stopAllAction();
      const a = mixer.clipAction(clip);
      a.play();
      a.time = t;
      mixer.update(0);
      scene.updateMatrixWorld(true);
    };
    const idle = animations.find((c) => c.name === "idle") ?? animations[0];
    pose(idle, 0);
    const box = new THREE.Box3().setFromObject(scene, true);
    const s = FIGURE_HEIGHT / (box.max.y - box.min.y);
    const origin = new THREE.Vector3((box.min.x + box.max.x) / 2, box.min.y, (box.min.z + box.max.z) / 2);
    const r3 = (v: number) => Math.round(v * 1000) / 1000;
    tracks[e.id] = {};
    for (const clip of animations) {
      const rows: number[][] = [];
      for (let i = 0; i <= Math.ceil(clip.duration * 30); i++) {
        pose(clip, Math.min(i / 30, clip.duration));
        const p = hips.getWorldPosition(new THREE.Vector3()).sub(origin).multiplyScalar(s);
        rows.push([r3(p.x), r3(p.y), r3(p.z)]);
      }
      tracks[e.id][clip.name] = rows;
    }
    log.ok(`${e.id}: hip tracks for ${animations.length} clips`);
  }
  await writeFile(OUT, JSON.stringify({ $comment: "Generated by scripts/qc/clip-tracks.ts — hips [x,y,z] per 1/30 s in figure space.", fps: 30, tracks }) + "\n");
  return tracks;
};

if (import.meta.url === `file://${process.argv[1]}`) await writeClipTracks();
